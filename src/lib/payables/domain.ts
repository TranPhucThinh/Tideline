import { isValidDateKey } from '../date.ts';

export type PayableKind = 'once' | 'installment' | 'subscription';
export interface SalarySetting { effective_from: string; day_start: number; default_income: number | null }
export interface SalaryCycle { start: string; end: string; income: number | null }
export interface PayableItem {
	id: string; name: string; provider: string; note: string; kind: PayableKind;
	amount: number; first_due: string; count: number | null; estimated: boolean; stop_from: string | null;
}
export interface PriceRevision { item_id: string; from_sequence: number; amount: number }
export interface PaymentOverride { item_id: string; sequence: number; amount: number; paid_on: string | null }
export interface Occurrence extends PayableItem { item_id: string; sequence: number; due: string; paid_on: string | null }
export interface IncomeOverride { cycle_start: string; amount: number | null }
export const kindLabels: Record<PayableKind, string> = { once: 'Trả một lần', installment: 'Trả góp', subscription: 'Định kỳ' };
export const statusLabels = { pending: 'Chưa đến hạn', soon: 'Sắp đến hạn', today: 'Đến hạn hôm nay', overdue: 'Quá hạn', paid: 'Đã trả' };

function key(d: Date): string { return d.toISOString().slice(0, 10); }
export function shiftDate(date: string, days: number): string {
	const d = new Date(`${date}T00:00:00Z`); d.setUTCDate(d.getUTCDate() + days); return key(d);
}
/** Always calculate from the original day, never from a clamped February occurrence. */
export function monthlyDate(anchor: string, offset: number): string {
	const [year, month, day] = anchor.split('-').map(Number);
	const first = new Date(Date.UTC(year, month - 1 + offset, 1));
	const last = new Date(Date.UTC(first.getUTCFullYear(), first.getUTCMonth() + 1, 0)).getUTCDate();
	first.setUTCDate(Math.min(day, last)); return key(first);
}
function monthAnchor(date: string, day: number, offset = 0): string {
	return monthlyDate(`${date.slice(0, 7)}-${String(day).padStart(2, '0')}`, offset);
}

/** Setting revisions start at the old cycle's next boundary; this preserves history. */
export function salaryCycle(date: string, settings: SalarySetting[]): SalaryCycle {
	const sorted = [...settings].sort((a, b) => a.effective_from.localeCompare(b.effective_from));
	const setting = sorted.filter(s => s.effective_from <= date).at(-1) ?? sorted[0] ?? { effective_from: '2000-01-01', day_start: 1, default_income: null };
	let start = monthAnchor(date, setting.day_start);
	if (start > date) start = monthAnchor(date, setting.day_start, -1);
	if (setting.effective_from <= date && start < setting.effective_from) start = setting.effective_from;
	let next = monthAnchor(start, setting.day_start);
	if (next <= start) next = monthAnchor(start, setting.day_start, 1);
	const revision = sorted.find(s => s.effective_from > date);
	if (revision && revision.effective_from < next) next = revision.effective_from;
	return { start, end: shiftDate(next, -1), income: setting.default_income };
}

/** Recurrences are projected, not generated by cron. Overrides have a stable item/sequence key. */
export function occurrences(items: PayableItem[], prices: PriceRevision[], overrides: PaymentOverride[], through: string): Occurrence[] {
	const byKey = new Map(overrides.map(o => [`${o.item_id}:${o.sequence}`, o]));
	const rows: Occurrence[] = [];
	for (const item of items) {
		const revisions = prices.filter(p => p.item_id === item.id).sort((a, b) => a.from_sequence - b.from_sequence);
		const max = item.kind === 'once' ? 1 : item.kind === 'installment' ? item.count ?? 0 : 1212;
		for (let sequence = 0; sequence < max; sequence++) {
			const due = monthlyDate(item.first_due, sequence);
			if (due > through) break;
			const override = byKey.get(`${item.id}:${sequence}`);
			if (item.stop_from && due >= item.stop_from && !override?.paid_on) continue;
			const amount = override?.amount ?? revisions.filter(r => r.from_sequence <= sequence).at(-1)?.amount ?? item.amount;
			rows.push({ ...item, item_id: item.id, id: `${item.id}:${sequence}`, sequence, due, amount, paid_on: override?.paid_on ?? null });
		}
	}
	return rows.sort((a, b) => a.due.localeCompare(b.due) || a.name.localeCompare(b.name) || a.id.localeCompare(b.id));
}

export function summarize(rows: Occurrence[], cycle: SalaryCycle, today: string) {
	const asOf = today < cycle.end ? today : cycle.end;
	const paidAt = (r: Occurrence) => r.paid_on !== null && r.paid_on <= asOf;
	const inCycle = rows.filter(r => r.due >= cycle.start && r.due <= cycle.end);
	const total = inCycle.reduce((sum, r) => sum + r.amount, 0);
	const paid = inCycle.filter(paidAt).reduce((sum, r) => sum + r.amount, 0);
	const arrearsRows = rows.filter(r => r.due < cycle.start && r.due < asOf && !paidAt(r));
	const arrears = arrearsRows.reduce((sum, r) => sum + r.amount, 0);
	const remaining = cycle.income === null ? null : cycle.income - total;
	return { total, paid, unpaid: total - paid, remaining, arrears, arrearsRows, afterArrears: remaining === null ? null : remaining - arrears, inCycle, asOf };
}
export function statusOf(row: Pick<Occurrence, 'due' | 'paid_on'>, today: string): keyof typeof statusLabels {
	if (row.paid_on && row.paid_on <= today) return 'paid';
	if (row.due < today) return 'overdue';
	if (row.due === today) return 'today';
	return row.due <= shiftDate(today, 7) ? 'soon' : 'pending';
}
export function simulateSavings(rows: Occurrence[], cycle: Pick<SalaryCycle, 'start' | 'end'>, selected: string[]): number {
	return rows.filter(r => r.kind === 'subscription' && selected.includes(r.item_id) && !r.paid_on && r.due >= cycle.start && r.due <= cycle.end).reduce((sum, r) => sum + r.amount, 0);
}
export function validateItem(item: Pick<PayableItem, 'name' | 'provider' | 'note' | 'kind' | 'amount' | 'first_due' | 'count'>): string | null {
	if (!item.name.trim() || item.name.length > 120) return 'Tên khoản cần có từ 1 đến 120 ký tự.';
	if (item.provider.length > 120 || item.note.length > 1000) return 'Nhà cung cấp tối đa 120 ký tự, ghi chú tối đa 1.000 ký tự.';
	if (!['once', 'installment', 'subscription'].includes(item.kind)) return 'Loại khoản không hợp lệ.';
	if (!Number.isSafeInteger(item.amount) || item.amount <= 0 || item.amount > 1_000_000_000_000) return 'Số tiền phải là số nguyên VND từ 1 đến 1.000 tỷ.';
	if (!isValidDateKey(item.first_due) || item.first_due < '2000-01-01' || item.first_due > '2100-12-31') return 'Ngày đến hạn phải hợp lệ, trong khoảng 2000–2100.';
	if (item.kind === 'installment' && (!Number.isInteger(item.count) || item.count! < 1 || item.count! > 600)) return 'Số lần trả góp phải từ 1 đến 600.';
	return null;
}
